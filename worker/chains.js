/* =====================================================================
   کدام زنجیره؟ — فقط از روی شکلِ خودِ آدرس، بدون هیچ فراخوانیِ شبکه
   =====================================================================
   تا امروز کل Worker فرض می‌کرد آدرس یعنی «آدرسِ Base» (۰x + ۴۰ رقمِ هگز):
   OG_NETWORK ثابت «base» بود و TOKEN_PAGE فقط همان یک شکل را می‌شناخت. با
   ورودِ سولانا این فرض دیگر درست نیست — یک mint سولانا اصلاً هگز نیست، یک
   رشته‌ی base58 با طولِ متغیر است. این ماژول همان یک تصمیم را از روی شکلِ
   رشته می‌گیرد، هیچ‌جای دیگر این تصمیم نباید دوباره گرفته شود.

   ⚠️ چرا این‌قدر روی «بدون‌ابهام‌بودن» تاکید می‌کنیم: اگر روزی یک رشته هم
   شکلِ Base را داشته باشد هم شکلِ سولانا را، chainOf باید همیشه یکی را
   بدهد، نه اینکه ترتیبِ چک‌کردن تصادفی تصمیم بگیرد. زیر هر الگو توضیح
   داده شده چرا چنین تلاقی‌ای هرگز رخ نمی‌دهد. */

/* آدرسِ Base — همان شکلِ همیشگی: ۰x + دقیقاً ۴۰ رقمِ هگز. */
export const EVM_ADDR = /^0x[0-9a-fA-F]{40}$/;

/* mint سولانا — base58، طولِ ۳۲ تا ۴۴ نویسه (یک کلیدِ عمومیِ ۳۲-بایتی وقتی
   base58 می‌شود بسته به تعداد بایتِ صفرِ ابتدایی همین بازه را می‌گیرد).
   الفبا عمداً چهار نویسه را ندارد: 0 (صفر)، O (اُ بزرگ)، I (آی بزرگ)، l (ال
   کوچک) — این چهار در بیشتر فونت‌ها با یک نویسه‌ی دیگر اشتباه گرفته
   می‌شوند و base58 دقیقاً برای همین حذفشان کرده. */
export const SOL_MINT = /^[1-9A-HJ-NP-Za-km-z]{32,44}$/;

/* ⚠️ اثباتِ بدون‌ابهامی: هر رشته‌ای که EVM_ADDR بپذیرد با «0x» شروع می‌شود،
   یعنی نویسه‌ی اولش «0» است. الفبای SOL_MINT اصلاً نویسه‌ی «0» ندارد — نه
   فقط در جایگاهِ اول، در هیچ جایگاهی. پس هیچ رشته‌ای که شکلِ Base دارد
   نمی‌تواند هم‌زمان شکلِ سولانا هم داشته باشد؛ این دو الگو ذاتاً جدا از
   همند، نه فقط در عمل. worker/test.mjs همین استدلال را روی چند نمونه
   می‌سنجد. */
export function chainOf(addr) {
  if (typeof addr !== "string") return null;
  if (EVM_ADDR.test(addr)) return "base";
  if (SOL_MINT.test(addr)) return "solana";
  return null;
}

/* زنجیره → شناسه‌ی شبکه‌ی GeckoTerminal. امروز این دو یکی‌اند («base»،
   «solana») ولی از رویِ یک جدولِ صریح می‌آید، نه از رویِ فرضِ «همیشه همینه» —
   اگر روزی GeckoTerminal شناسه‌ی دیگری برای یک زنجیره خواست، فقط همین جدول
   عوض می‌شود. زنجیره‌ی ناشناخته → null، نه یک رشته‌ی حدسی. */
const GT_NETWORK_BY_CHAIN = { base: "base", solana: "solana" };
export function gtNetworkOf(chain) {
  return Object.prototype.hasOwnProperty.call(GT_NETWORK_BY_CHAIN, chain)
    ? GT_NETWORK_BY_CHAIN[chain]
    : null;
}
