#!/usr/bin/env node
/* Zaexa — build _site for Cloudflare (replaces the hand-written cp line in the panel).
 *
 * Why (3 Nov 2026): on Hesam's network in Iran the browser often stalls or silently truncates the
 * ~890KB app document (~270KB brotli) somewhere after ~200KB, so the big inline app script never
 * arrives and the Swap/Markets/Stocks buttons stay dead. Small responses (/report, the landing page)
 * always arrive. So the built app.html keeps everything except the main app script, and that script
 * is served as a few content-hashed chunks (each well under 50KB compressed) that a tiny loader
 * fetches with a timeout and retries, joins and runs. Chunks are immutable (/*.js in _headers), so a
 * second visit costs nothing.
 *
 * The source of truth stays web/index.html — the test suite keeps reading it unchanged; only the
 * deployed copy is split.
 *
 * Usage: node scripts/build_site.mjs [--src web] [--out _site] [--index <path to app html>]
 */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const args = process.argv.slice(2);
const opt = (name, def) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : def; };
const SRC = opt("--src", "web");
const OUT = opt("--out", "_site");
const INDEX = opt("--index", path.join(SRC, "index.html"));
export const CHUNK_CHARS = 110000;          // ~25–30KB brotli each
const MAIN_MARK = "از پایتون ترجمه شده";       // a line in the header comment of the main app script

/* ۳ نوامبر — شبکه‌ی حسام هر اتصال به IPهای کلادفلرِ این زون را بعد از حدودِ ۱۲۰KB (فشرده) می‌خواباند (سنجیده با
   curl روی یک اتصالِ مشترک: دو پاسخ، بعد صفر بایت). پس بایت مهم است: کامنت‌های اسکریپتِ اصلی (بیشترش فارسی) با
   terser فقط حذف می‌شوند — بدونِ compress و mangle، یعنی کد دست نمی‌خورد — و کامنت‌های CSS/HTML بیرون از
   اسکریپت‌ها هم. اگر terser نصب نبود، ساخت بی‌کوچک‌سازی ادامه می‌دهد (فقط هشدار). */
export async function stripJsComments(code) {
  let terser;
  try { terser = await import("terser"); } catch (e) { console.warn("build_site: terser not installed — app script not minified"); return code; }
  const r = await terser.minify(code, { compress: false, mangle: false, format: { comments: false } });
  if (!r || typeof r.code !== "string" || !r.code) throw new Error("terser returned no code");
  return r.code;
}

export function stripMarkupComments(html) {
  // فقط بیرون از <script>: کامنتِ HTML، و کامنتِ CSS داخلِ <style>
  return html.split(/(<script[\s\S]*?<\/script>)/).map((part, i) => {
    if (i % 2 === 1) return part;
    return part
      .replace(/<!--[\s\S]*?-->/g, "")
      .replace(/(<style[^>]*>)([\s\S]*?)(<\/style>)/g, (m, a, css, b) => a + css.replace(/\/\*[\s\S]*?\*\//g, "") + b);
  }).join("");
}

export function splitApp(html, chunkChars = CHUNK_CHARS, transformBody = (b) => b) {
  const at = html.indexOf(MAIN_MARK);
  if (at < 0) throw new Error("main app script marker not found");
  const open = html.lastIndexOf("<script>", at);
  const close = html.indexOf("</script>", at);
  if (open < 0 || close < 0) throw new Error("main app script tags not found");
  if (html.indexOf(MAIN_MARK, close) >= 0) throw new Error("main app script marker appears twice");
  const body = transformBody(html.slice(open + "<script>".length, close));
  const hash = crypto.createHash("sha256").update(body).digest("hex").slice(0, 10);
  const chunks = [];
  // Cut only after a newline: never inside a surrogate pair or a multi-byte character.
  for (let i = 0; i < body.length;) {
    let j = Math.min(body.length, i + chunkChars);
    if (j < body.length) { const nl = body.lastIndexOf("\n", j); if (nl > i) j = nl + 1; }
    chunks.push(body.slice(i, j));
    i = j;
  }
  const names = chunks.map((_, i) => `app.${hash}.${i}.js`);
  const loader = loaderScript(names.map((n) => "/" + n), chunks.map((c) => c.length));
  const out = stripMarkupComments(html.slice(0, open)) + loader + stripMarkupComments(html.slice(close + "</script>".length));
  return { html: out, chunks, names, body, hash };
}

/* Inline loader. No literal closing script tag inside (it would end the element early). */
function loaderScript(paths, lens) {
  return "<script>\n/* ZX-CHUNK-LOADER — generated by scripts/build_site.mjs; see the comment there. */\n" +
"(function(){\n" +
"  var P=" + JSON.stringify(paths) + ",L=" + JSON.stringify(lens) + ";\n" +
"  var parts=new Array(P.length),got=0,next=0,dead=false,TIMEOUT=8000,TRIES=6,CONC=2;\n" +
"  function get(i,k){\n" +
"    var ac=window.AbortController?new AbortController():null;\n" +
"    var t=setTimeout(function(){if(ac)ac.abort()},TIMEOUT);\n" +
"    fetch(P[i],{credentials:\"same-origin\",signal:ac?ac.signal:undefined})\n" +
"      .then(function(r){if(!r.ok)throw 0;return r.text()})\n" +
"      .then(function(x){clearTimeout(t);if(x.length!==L[i])throw 0;parts[i]=x;got++;\n" +
"        if(got===P.length)run();else pump();})\n" +
"      .catch(function(){clearTimeout(t);if(k+1<TRIES)setTimeout(function(){get(i,k+1)},400*(k+1));else fail();});\n" +
"  }\n" +
"  function pump(){while(next<P.length&&next-got<CONC){get(next++,0)}}\n" +
"  function run(){var s=document.createElement(\"script\");s.textContent=parts.join(\"\");document.body.appendChild(s);window.__zxApp=1;}\n" +
"  function fail(){if(dead)return;dead=true;var K=\"zaexa.chunkretry\",c=0;\n" +
"    try{c=+(sessionStorage.getItem(K)||0)}catch(e){return}\n" +
"    if(c<1){try{sessionStorage.setItem(K,\"1\")}catch(e){return}location.reload();}}\n" +
"  try{sessionStorage.removeItem(\"zaexa.chunkretry\")}catch(e){}\n" +
"  pump();\n" +
"})();\n" +
"</script>";
}

function copy(from, to) { fs.copyFileSync(from, to); }

export async function build() {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });
  const src = fs.readFileSync(INDEX, "utf8");
  const at = src.indexOf(MAIN_MARK), o = src.lastIndexOf("<script>", at), c = src.indexOf("</script>", at);
  const small = await stripJsComments(src.slice(o + "<script>".length, c));
  const app = splitApp(src, CHUNK_CHARS, () => small);
  fs.writeFileSync(path.join(OUT, "app.html"), app.html);
  app.chunks.forEach((c, i) => fs.writeFileSync(path.join(OUT, app.names[i]), c));
  copy(path.join(SRC, "landing.html"), path.join(OUT, "index.html"));
  for (const f of fs.readdirSync(SRC)) {
    const p = path.join(SRC, f);
    if (!fs.statSync(p).isFile()) continue;
    if (f === "index.html" || f === "landing.html") continue;
    if (f.endsWith(".html") || f.endsWith(".js") || f === "_headers") copy(p, path.join(OUT, f));
  }
  return app;
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith("build_site.mjs")) {
  const app = await build();
  console.log(`_site built: app.html ${Buffer.byteLength(app.html)}B + ${app.chunks.length} chunks (${app.hash})`);
}
